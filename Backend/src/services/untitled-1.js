// At its core, an **interview** is a structured conversation where one person (or a group of people) asks questions, and another person answers them. The goal is to gather information, assess qualifications, or learn more about a person’s experiences and opinions.

// Here is a breakdown of how interviews work, the different types, and why they are important.

// ---

// ### 1. The Key Players
// Every interview has two main roles:
// *   **The Interviewer:** The person who guides the conversation, asks the questions, and listens to the answers.
// *   **The Interviewee:** The person who answers the questions and shares their knowledge, story, or qualifications.

// ### 2. Common Types of Interviews
// While most people think of job hunting when they hear the word "interview," they are used in many different fields:

// *   **Job Interviews:** A employer interviews a job applicant to see if they have the right skills, personality, and experience for the role.
// *   **Journalistic/Media Interviews:** A reporter or podcast host interviews a politician, celebrity, or expert to get information, opinions, or stories for the public.
// *   **Research/Academic Interviews:** A researcher interviews people to gather qualitative data for a scientific study, market research, or historical project.
// *   **Informational Interviews:** An informal chat where someone seeking career advice talks to an experienced professional to learn about their industry.
// *   **Admissions Interviews:** Used by universities or private schools to evaluate prospective students.

// ### 3. Different Formats
// Interviews don't just happen in quiet office rooms anymore. They can take place in several ways:
// *   **In-Person:** Face-to-face, which allows both parties to read body language.
// *   **Video (Virtual):** Done over platforms like Zoom, Teams, or Google Meet.
// *   **Phone:** Often used as a quick first step to screen candidates.
// *   **Panel:** Where one interviewee is questioned by a group of interviewers.

// ### 4. Why are Interviews Useful?
// Interviews are valuable because they go beyond what can be written on paper (like a résumé or a written survey). They allow the interviewer to:
// *   Assess communication skills and personality.
// *   Ask follow-up questions to dig deeper into an answer.
// *   See how the interviewee thinks on their feet.

// **Pro-Tip:** A great interview is actually a **two-way street**. Especially in job interviews, it is just as much an opportunity for the interviewee to ask questions and decide if the company is a good fit for *them*!